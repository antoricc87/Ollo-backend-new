/** Every optional test for this person: not already in their plan, relevant ones first. */
export const optionalFor = (p: ScreeningProfile, inPlan: Set<string>): OptionalItem[] => {
  const out = OPTIONAL.filter((e) => adult(p) && (e.applies ? e.applies(p) : true) && !inPlan.has(e.key))
    .map(({ applies, relevant, ...e }) => ({ ...e, tags: relevant ? relevant(p) : [] }));
  return [...out.filter((o) => o.tags.length), ...out.filter((o) => !o.tags.length)];
};
