/**
 * ADDITIONAL TESTS YOU CAN ADD — every other preventive test Ollo offers
 * (his ruling Nov 19 2026: "any other additional preventive test"), outside
 * routine guidelines for this person. Each says what it CHECKS and WHY it is
 * OPTIONAL — what it adds and what to weigh — so "optional" never reads as
 * "secretly recommended". Prices are DIRECTIONAL (US cash prices, rounded)
 * until real providers price them.
 *
 * `relevant(p)` returns the reasons this test relates to the person (a family
 * history, a condition, an age); relevant tests are listed first. `applies`
 * hides a test that makes no sense for them (a mammogram for a man).
 * A test the guideline rules already put in the plan is never repeated here.
 *
 * NEEDS CLINICAL REVIEW (copy, relevance and prices).
 */

type Entry = Omit<OptionalItem, "tags"> & {
  applies?: (p: ScreeningProfile) => boolean;
  relevant?: (p: ScreeningProfile) => Tag[];
};

const has = (list: string[], ...k: string[]) => list.some((x) => k.some((w) => x.includes(w)));
const heartFamily = (p: ScreeningProfile): Tag[] =>
  p.family.earlyHeartDisease ? [{ key: "family", text: "Family history" }] : p.family.highCholesterol ? [{ key: "family", text: "Family history" }] : has(p.conditions, "cholesterol", "hyperlipid") ? [{ key: "condition", text: "Your record" }] : [];
const metabolicRisk = (p: ScreeningProfile): Tag[] =>
  p.family.diabetes ? [{ key: "family", text: "Family history" }] : (p.bmi ?? 0) >= 27 || has(p.conditions, "prediabet", "insulin resistance", "pcos") ? [{ key: "condition", text: "Your record" }] : [];
const female = (p: ScreeningProfile) => p.sex === "female";
const male = (p: ScreeningProfile) => p.sex === "male";
const adult = (p: ScreeningProfile) => p.age === null || p.age >= 18;
const src = (org: string, year: number, grade?: string): Source => ({ org, year, ...(grade ? { grade } : {}) });

